const getProvider = player => {
  const normalized = player.toLowerCase();

  if (normalized.startsWith('kata1-')) return 'katago';
  if (normalized.startsWith('opus-')) return 'anthropic';
  if (normalized.startsWith('gemini-')) return 'google';
  if (normalized.startsWith('deepseek-')) return 'deepseek';
  if (normalized.startsWith('kimi-')) return 'moonshot';
  if (normalized.startsWith('gpt')) return 'openai';
  if (normalized.startsWith('muse-')) return 'meta';
  if (normalized.startsWith('grok-')) return 'xai';

  return 'unknown';
};

