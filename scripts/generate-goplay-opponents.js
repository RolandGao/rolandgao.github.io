const fs = require('fs');
const path = require('path');
const supplement = require('../public/data/goplay_players.json');
const base = require('../public/data/gobench_data/paper_results.json');

// Keep GoBench's current ratings authoritative and avoid bundling its game
// records into GoPlay. Supplemental ratings fill gaps in the paper dataset.
const players = new Map();
for (const { player, elo, elo_ci_95 } of [
  ...supplement.players,
  ...base.datasets.katago_players,
]) {
  if (/^kata1-b6c96-/.test(player)) {
    players.set(player, { player, elo, elo_ci_95 });
  }
}

fs.writeFileSync(
  path.join(__dirname, '../public/data/goplay_opponents.json'),
  `${JSON.stringify({
    schema_version: 1,
    source: 'Generated by scripts/generate-goplay-opponents.js from GoBench and supplemental GoPlay ratings',
    players: [...players.values()].sort((left, right) => left.elo - right.elo),
  }, null, 2)}\n`,
);
